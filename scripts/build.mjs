/**
 * Build `lib/client.js` from the extracted English dictionaries and the
 * Spanish translations in `translations/es`.
 *
 * The DSH client module system serves one prebuilt bundle per package and
 * executes it as `window.__ModuleLoader__.load({ id, factory })`, so the
 * dictionaries are inlined into the factory closure. This script is also the
 * quality gate: it refuses to emit a bundle when a namespace is missing, a key
 * is absent, an unknown key was added, or a `{placeholder}` differs from the
 * English source.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const enDir = path.join(root, 'translations', 'en')
const esDir = path.join(root, 'translations', 'es')

export const LOCALE = 'es-419'
export const LOCALE_LABEL = 'Español (Latinoamérica)'

const PLACEHOLDER = /\{([A-Za-z0-9_.]+)\}/g

function placeholders(value) {
  return [...value.matchAll(PLACEHOLDER)].map((match) => match[1]).sort()
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

const problems = []
const warnings = []
const namespaces = []

for (const file of fs.readdirSync(enDir).filter((name) => name.endsWith('.json')).sort()) {
  const ns = file.slice(0, -'.json'.length)
  const en = readJson(path.join(enDir, file))
  const esPath = path.join(esDir, file)
  if (!fs.existsSync(esPath)) {
    problems.push(`${ns}: no Spanish file at translations/es/${file}`)
    continue
  }
  const es = readJson(esPath)
  const enKeys = Object.keys(en)
  const esKeys = Object.keys(es)
  const missing = enKeys.filter((key) => !(key in es))
  const extra = esKeys.filter((key) => !(key in en))
  if (missing.length > 0) problems.push(`${ns}: ${missing.length} missing keys (${missing.slice(0, 6).join(', ')})`)
  if (extra.length > 0) problems.push(`${ns}: ${extra.length} unknown keys (${extra.slice(0, 6).join(', ')})`)

  const dictionary = {}
  let translated = 0
  for (const key of enKeys) {
    const source = en[key]
    if (typeof source !== 'string') {
      problems.push(`${ns}/${key}: English source is not a string`)
      continue
    }
    const value = es[key]
    const sourceIsBlank = source.trim() === ''
    if (typeof value !== 'string' || (value.trim() === '' && !sourceIsBlank)) {
      if (key in es) problems.push(`${ns}/${key}: empty translation`)
      continue
    }
    const expected = placeholders(source)
    const actual = placeholders(value)
    if (expected.join(',') !== actual.join(',')) {
      problems.push(`${ns}/${key}: placeholders {${expected.join('}, {')}} replaced by {${actual.join('}, {')}}`)
      continue
    }
    if (value !== source) translated += 1
    else if (/^[\d\s.:%/-]+$/u.test(source) === false) warnings.push(`${ns}/${key}: identical to English`)
    dictionary[key] = value
  }
  namespaces.push({ ns, en: enKeys.length, dictionary, translated })
}

const keyCount = namespaces.reduce((sum, entry) => sum + Object.keys(entry.dictionary).length, 0)
const identical = warnings.length

if (problems.length > 0) {
  console.error(`dsh-locale-es: ${problems.length} problem(s) across ${namespaces.length} namespaces:\n`)
  for (const problem of problems) console.error(`  - ${problem}`)
  process.exit(1)
}

const payload = namespaces
  .map(({ ns, dictionary }) => `\t${JSON.stringify(ns)}: ${JSON.stringify(dictionary)}`)
  .join(',\n')

const bundle = `/**
 * dsh-locale-es — ${LOCALE_LABEL} (${LOCALE}) language pack for DeepSeek Harness.
 *
 * Generated by scripts/build.mjs from translations/en + translations/es.
 * Do not edit by hand: edit the translation JSON and rebuild.
 *
 * The bundle only registers factories: every side effect lives in the factory
 * closure and runs when the client module system materializes the package.
 */
window.__ModuleLoader__.load({
\tid: "dsh-locale-es",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

\t\t/** BCP 47 id of the language pack this bundle contributes. */
\t\tconst LOCALE = ${JSON.stringify(LOCALE)};
\t\t/** Label shown in Settings → General → Language. */
\t\tconst LABEL = ${JSON.stringify(LOCALE_LABEL)};
\t\t/** Language whose copy answers a key the Spanish dictionary lacks. */
\t\tconst FALLBACK = "en";
\t\t/** Spanish dictionaries, one entry per locale namespace owned by the UI. */
\t\tconst DICTIONARIES = {
${payload}
\t\t};

\t\t/** Register the language pack and every dictionary as owned effects. */
\t\tfunction apply(ctx) {
\t\t\tctx.effect(
\t\t\t\t() => ctx.locale.addLanguage({ id: LOCALE, label: LABEL, fallback: FALLBACK }),
\t\t\t\t"locale-es: language definition",
\t\t\t);
\t\t\tfor (const [namespace, dictionary] of Object.entries(DICTIONARIES)) {
\t\t\t\tctx.effect(
\t\t\t\t\t() => ctx.locale.register(namespace, LOCALE, dictionary),
\t\t\t\t\t\`locale-es: \${namespace} dictionary\`,
\t\t\t\t);
\t\t\t}
\t\t}

\t\texports.apply = apply;
\t\texports.inject = ["locale"];
\t\treturn module.exports;
\t}
});
`

fs.mkdirSync(path.join(root, 'lib'), { recursive: true })
fs.writeFileSync(path.join(root, 'lib', 'client.js'), bundle)

const bytes = Buffer.byteLength(bundle)
console.log(
  `dsh-locale-es: ${namespaces.length} namespaces, ${keyCount} keys, ${translatedSummary(namespaces)}, ${(bytes / 1024).toFixed(1)} KiB`,
)
if (identical > 0) console.log(`  ${identical} key(s) kept identical to English (technical terms)`)
console.log('  wrote lib/client.js')

function translatedSummary(entries) {
  const total = entries.reduce((sum, entry) => sum + entry.en, 0)
  const changed = entries.reduce((sum, entry) => sum + entry.translated, 0)
  return `${changed} key(s) localized (${total - changed} kept identical)`
}
